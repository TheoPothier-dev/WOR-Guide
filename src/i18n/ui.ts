export type UiKey = keyof (typeof ui)['en'];

export function useTranslations(lang: Locale) {
  return (key: UiKey): string => ui[lang][key] ?? ui[defaultLocale as Locale][key];
}

// Texte localisé venant des données : { en: '...', fr: '...' }. Retombe sur l'anglais.
export type LocalizedText = Partial<Record<Locale, string>> & { en: string };

export function localize(text: LocalizedText, lang: Locale): string {
  return text[lang] ?? text.en;
}
